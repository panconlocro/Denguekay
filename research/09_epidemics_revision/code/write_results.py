"""Write the result tables of RESULTS.md from the CSV outputs, so the document can't drift from the results."""

import re
from pathlib import Path

import pandas as pd

import common as c

RES = c.OUTPUT / "resultados"
TARGET = c.STUDY / "RESULTS_TABLES.md"


def interval(text) -> str:
    """``(lo, hi)`` as written by ``experiments.contrast`` (also tolerates ``np.float64(...)`` reprs)."""
    lo, hi = (float(x) for x in re.findall(r"-?\d+(?:\.\d+)?(?:e[-+]?\d+)?", text.replace("np.float64", ""))) if isinstance(text, str) else text
    return f"{lo:+.2f} to {hi:+.2f}"


def contrast_table(frame: pd.DataFrame, label_column: str | None = None) -> str:
    rows = ["| " + " | ".join(([label_column] if label_column else []) + ["h", "Pooled change", "95% interval",
            "Equal-season change", "Seasons first arm better"]) + " |",
            "|" + "---|" * (6 if label_column else 5)]
    for _, r in frame.iterrows():
        cells = ([str(r[label_column])] if label_column else []) + [
            str(int(r.horizonte)), f"{r['cambio_agrupado_%']:+.2f}%", interval(r["ic95_agrupado"]),
            f"{r['cambio_igual_peso_%']:+.2f}%", f"{int(r['temporadas_a_mejor'])} of {int(r.get('temporadas', 18))}"]
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def main():
    read = lambda name: pd.read_csv(RES / name)
    parts = ["# Result tables (generated by `code/write_results.py`)",
             "Negative change favours the first arm. 18 seasons (2009–2026) unless stated; pooled over district-weeks, "
             "median over seeds; 95% whole-season bootstrap."]
    e1 = read("e1_principal_18_temporadas.csv")
    for title, name in (("E1 · Climate effect: b3 vs history+geography", "b3 vs history+geography (climate effect)"),
                        ("E1 · b3 vs probabilistic persistence", "b3 vs probabilistic persistence"),
                        ("E1 · History+geography vs probabilistic persistence", "history+geography vs probabilistic persistence"),
                        ("E1 · b3 vs district climatology", "b3 vs climatology")):
        parts += [f"## {title}", contrast_table(e1[e1.comparacion.eq(name)])]
    seasons = read("e1_por_temporada.csv")
    s4 = seasons[seasons.horizonte.eq(4)]
    parts += ["## E1 · Climate effect by season (4 weeks)",
              "| Season | " + " | ".join(str(int(s)) for s in s4.temporada) + " |",
              "|---|" + "---|" * len(s4),
              "| Elevated weeks (%) | " + " | ".join(f"{v:.1f}" for v in s4["prevalencia_%"]) + " |",
              "| Brier change (%) | " + " | ".join(f"{v:+.1f}" for v in s4["cambio_%"]) + " |"]
    lags = read("e2_rezagos.csv")
    parts += ["## E2 · Weather lag (vs history+geography)", contrast_table(lags, "arm").replace("| arm |", "| Arm |")
              + "\n\nRows alternate between 18 seasons and the paper's 6 decision seasons (column `seasons` in `e2_rezagos.csv`)."]
    lags18 = lags[lags.seasons.eq("18 seasons")]
    parts += ["### E2 · 18 seasons only", contrast_table(lags18, "arm")]
    placebos = read("e2_placebos.csv").dropna(subset=["ic95_agrupado"])
    parts += ["## E2 · Observed weather vs wrong-year placebos (lag 2)", contrast_table(placebos, "placebo")]
    cal = read("e4_contrastes.csv")
    parts += ["## E4 · Climate effect under three calibrations", contrast_table(cal, "variant")]
    dec = read("e5_descomposicion.csv")
    parts += ["## E5 · What carries the skill", contrast_table(dec, "contrast")]
    for title, name in (("E6b · Confirmed + probable cases", "e6b_confirmados_probables.csv"),
                        ("E6c · Threshold without epidemic years", "e6c_umbral_sin_epidemias.csv"),
                        ("E6d · Incidence ≥ 10 per 100,000 (seasons 2019–2025)", "e6d_incidencia.csv")):
        t = read(name)
        if "seasons" in t:
            t = t.assign(comparison=t.seasons + " · " + t.comparison)
        parts += [f"## {title}", contrast_table(t, "comparison")]
    nb2 = read("e7_nb2.csv")
    parts += ["## E7 · NB2 regression", contrast_table(nb2, "comparison")]
    long = read("e8_principal.csv")
    parts += ["## E8 · 8 and 12 weeks (separate two-output model)", contrast_table(long, "comparacion")]
    parts += ["# E9–E13 · Checks requested by external feedback (`protocolo_revision.md`; exploratory)"]
    parts += ["## E9 · Weather alignments compared directly", contrast_table(read("e9_alineaciones_directas.csv"), "comparison")]
    split = read("e9_temporadas_desarrollo.csv")
    parts += ["## E9 · Development seasons (2010, 2015, 2016, 2022, 2023, 2026) and the other twelve",
              contrast_table(split.assign(comparison=split.seasons + " · " + split.comparison), "comparison")]
    counts = read("e10_conteos_incertidumbre.csv")
    parts += ["## E10 · Count MAE (published count): pooled relative change",
              contrast_table(counts.assign(comparison=counts.group + " · " + counts.comparison), "comparison")]
    without = read("e10_conteos_sin_temporada_dominante.csv")
    parts += ["## E10 · Count MAE without the season whose omission changes it most",
              contrast_table(without.assign(comparison=without.group + " · " + without.comparison), "comparison")]
    state = read("e11_brier_por_estado.csv")
    parts += ["## E11 · Brier score by origin state (quiet: no elevated week in the four weeks up to the origin)",
              contrast_table(state.assign(comparison=state.state + " · " + state.comparison), "comparison")]
    fixed = read("e11_alertas_umbral_fijo.csv")
    rows = ["| Policy | Threshold | Model | Detected | False alarms per district-year | Mean warning (weeks) |",
            "|---|---|---|---|---|---|"]
    for _, r in fixed.iterrows():
        warning = f"{r.semanas_aviso_media:.2f}" if pd.notna(r.semanas_aviso_media) else "–"
        rows.append(f"| {r.policy} | {r.umbral:.1f} | {r.model} | {r['detectados_%']:.1f}% | {r.falsas_alarmas:.2f} | {warning} |")
    parts += ["## E11 · Onset weeks at fixed thresholds (detection and false alarms under the same policy; amendment 1)",
              "\n".join(rows)]
    levels = read("e11_deteccion_presupuesto.csv")
    wide = levels.pivot_table(index=["policy", "presupuesto"], columns="modelo", values="detectados_%").reset_index()
    rows = ["| Policy | False alarms per district-year | Climate | No climate | Persistence |", "|---|---|---|---|---|"]
    for _, r in wide.iterrows():
        rows.append(f"| {r.policy} | {r.presupuesto:.0f} | {r.climate:.1f}% | {r['no climate']:.1f}% | {r.persistence:.1f}% |")
    parts += ["## E11 · Onsets detected at matched false-alarm budgets", "\n".join(rows)]
    det = read("e11_deteccion_presupuesto_contrastes.csv")
    rows = ["| Policy | Comparison | False alarms per district-year | Difference (percentage points) | 95% interval | Seasons first better |",
            "|---|---|---|---|---|---|"]
    for _, r in det.iterrows():
        rows.append(f"| {r.policy} | {r.comparacion} | {r.presupuesto:.0f} | {r.diferencia_pp:+.2f} | {interval(r.ic95)} | "
                    f"{int(r.temporadas_a_mejor)} of {int(r.temporadas_con_inicios)} |")
    parts += ["## E11 · Onset detection compared at matched budgets", "\n".join(rows)]
    delays = read("e12_retrasos.csv")
    parts += ["## E12 · Simulated reporting delays", contrast_table(delays.assign(comparison=delays.scenario + " · " + delays.comparison), "comparison")]
    parts += ["## E13 · Direct classifier (formulation S3)", contrast_table(read("e13_clasificador.csv"), "comparison")]
    TARGET.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(TARGET)


if __name__ == "__main__":
    main()
